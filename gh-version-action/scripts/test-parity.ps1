#!/usr/bin/env pwsh
<#
.SYNOPSIS
Compares the Pester test inventory (Describe/Context/It names) with the Go subtests and reports unmapped PowerShell tests.

.DESCRIPTION
A PowerShell test is mapped when a Go test/subtest name contains every literal fragment of its name (<placeholders> of
parameterized tests are wildcards), compared case-insensitively on alphanumerics only. Tests that have no Go subtest of
the same name can be mapped explicitly in docs/test-parity-overrides.json (path pattern + optional test regex ->
category + note). Every unmapped test must end up with a justification category (na, covered, todo).

.PARAMETER WriteDoc
Regenerates docs/test-parity.md.

.PARAMETER Strict
Exit 1 when a PowerShell test is neither mapped nor justified (CI gate while the PowerShell code still exists).
#>
[CmdletBinding()]
param(
    [switch]$WriteDoc,
    [switch]$Strict,
    [string]$RepoRoot = (Resolve-Path (Join-Path $PSScriptRoot '../..')).Path
)

$ErrorActionPreference = 'Stop'
$goRoot = Join-Path $RepoRoot 'gh-version-action'
$overridesPath = Join-Path $goRoot 'docs/test-parity-overrides.json'

function ConvertTo-Key([string]$s) { ($s.ToLowerInvariant() -replace '[^\p{L}\p{N}]', '') }

# --- PowerShell inventory ---
$psFiles = Get-ChildItem -Path (Join-Path $RepoRoot 'tests'), (Join-Path $RepoRoot 'lib') -Recurse -Filter '*.Tests.ps1' -File |
    Sort-Object FullName
$rx = [regex]'^\s*(Describe|Context|It)\s+(?:-Name\s+)?(?<q>["''])(?<name>.*?)\k<q>'
$psTests = foreach ($f in $psFiles) {
    $rel = $f.FullName.Substring($RepoRoot.Length + 1).Replace('\', '/')
    foreach ($line in Get-Content $f.FullName) {
        $m = $rx.Match($line)
        if (-not $m.Success) { continue }
        [pscustomobject]@{ File = $rel; Kind = $m.Groups[1].Value; Name = $m.Groups['name'].Value }
    }
}

# --- Go inventory ---
Push-Location $goRoot
try {
    $raw = & go test -v -count=1 -run . ./... 2>&1
} finally { Pop-Location }
$goNames = [System.Collections.Generic.HashSet[string]]::new()
$goKeys = [System.Collections.Generic.List[object]]::new()
foreach ($l in $raw) {
    if ("$l" -match '^\s*=== RUN\s+(\S+)') {
        $n = $Matches[1]
        if ($goNames.Add($n)) { $goKeys.Add([pscustomobject]@{ Name = $n; Key = (ConvertTo-Key $n) }) }
    }
}

$overrides = @()
if (Test-Path $overridesPath) { $overrides = Get-Content $overridesPath -Raw | ConvertFrom-Json }

function Find-GoMatch([string]$name) {
    $parts = @([regex]::Split($name, '<[^>]+>') | ForEach-Object { ConvertTo-Key $_ } | Where-Object { $_ })
    if ($parts.Count -eq 0) { return $null }
    foreach ($g in $goKeys) {
        $pos = 0; $ok = $true
        foreach ($p in $parts) {
            $i = $g.Key.IndexOf($p, $pos, [StringComparison]::Ordinal)
            if ($i -lt 0) { $ok = $false; break }
            $pos = $i + $p.Length
        }
        if ($ok) { return $g.Name }
    }
    return $null
}

$rows = foreach ($t in $psTests) {
    $status = 'unmapped'; $go = ''; $note = ''
    if ($t.Kind -eq 'It') {
        $go = Find-GoMatch $t.Name
        if ($go) { $status = 'mapped' }
    } else {
        $status = 'container'
    }
    if ($status -eq 'unmapped') {
        foreach ($o in $overrides) {
            if ($t.File -like $o.path -and (-not $o.test -or $t.Name -match $o.test)) {
                $status = $o.category; $note = $o.note; $go = $o.go; break
            }
        }
    }
    [pscustomobject]@{ File = $t.File; Kind = $t.Kind; Name = $t.Name; Status = $status; Go = $go; Note = $note }
}

$its = @($rows | Where-Object Kind -eq 'It')
$summary = [ordered]@{
    'PowerShell test files' = $psFiles.Count
    'PowerShell It blocks' = $its.Count
    'Mapped to a Go subtest by name' = @($its | Where-Object Status -eq 'mapped').Count
    'Justified: covered elsewhere' = @($its | Where-Object Status -eq 'covered').Count
    'Justified: N/A (PowerShell-specific)' = @($its | Where-Object Status -eq 'na').Count
    'TODO (not ported yet)' = @($its | Where-Object Status -eq 'todo').Count
    'Unmapped and unjustified' = @($its | Where-Object Status -eq 'unmapped').Count
    'Go tests and subtests' = $goNames.Count
}
$summary.GetEnumerator() | ForEach-Object { Write-Host ('{0,-40} {1}' -f $_.Key, $_.Value) }

$unmapped = @($its | Where-Object { $_.Status -ne 'mapped' })
if ($unmapped.Count) {
    Write-Host "`nNot mapped by name ($($unmapped.Count)):"
    $unmapped | Group-Object File | ForEach-Object {
        Write-Host "  $($_.Name)"
        $_.Group | ForEach-Object { Write-Host ("    [{0}] {1}" -f $_.Status, $_.Name) }
    }
}

if ($WriteDoc) {
    $sb = [System.Text.StringBuilder]::new()
    [void]$sb.AppendLine('# Test parity: PowerShell (Pester) -> Go')
    [void]$sb.AppendLine()
    [void]$sb.AppendLine('Generated by `scripts/test-parity.ps1 -WriteDoc`; do not edit by hand. Explicit justifications live in')
    [void]$sb.AppendLine('`docs/test-parity-overrides.json`. A PowerShell `It` is *mapped* when a Go subtest contains every literal fragment of its')
    [void]$sb.AppendLine('name (parameterized `<placeholders>` are wildcards), compared case-insensitively on alphanumerics.')
    [void]$sb.AppendLine()
    [void]$sb.AppendLine('## Counts')
    [void]$sb.AppendLine()
    [void]$sb.AppendLine('| Metric | Count |')
    [void]$sb.AppendLine('|---|---|')
    foreach ($e in $summary.GetEnumerator()) { [void]$sb.AppendLine("| $($e.Key) | $($e.Value) |") }
    [void]$sb.AppendLine()
    [void]$sb.AppendLine('Categories: **na** = PowerShell-specific (class reloading, `Invoke-WebRequestWrapper` mocking, Pester plumbing);')
    [void]$sb.AppendLine('**covered** = behavior is verified by a differently named Go test; **todo** = real gap, not ported yet.')
    [void]$sb.AppendLine()
    [void]$sb.AppendLine('## Unmapped by name')
    [void]$sb.AppendLine()
    if (-not $unmapped.Count) { [void]$sb.AppendLine('None.') }
    foreach ($g in ($unmapped | Group-Object File)) {
        [void]$sb.AppendLine("### ``$($g.Name)``")
        [void]$sb.AppendLine()
        [void]$sb.AppendLine('| Category | PowerShell test | Go / justification |')
        [void]$sb.AppendLine('|---|---|---|')
        foreach ($r in $g.Group) {
            $just = (@($r.Go, $r.Note) | Where-Object { $_ }) -join ' - '
            [void]$sb.AppendLine(('| {0} | {1} | {2} |' -f $r.Status, $r.Name.Replace('|', '\|'), $just.Replace('|', '\|')))
        }
        [void]$sb.AppendLine()
    }
    [void]$sb.AppendLine('## Full mapping')
    [void]$sb.AppendLine()
    foreach ($g in ($its | Where-Object Status -eq 'mapped' | Group-Object File)) {
        [void]$sb.AppendLine("<details><summary><code>$($g.Name)</code> ($($g.Count))</summary>")
        [void]$sb.AppendLine()
        [void]$sb.AppendLine('| PowerShell test | Go subtest |')
        [void]$sb.AppendLine('|---|---|')
        foreach ($r in $g.Group) { [void]$sb.AppendLine(('| {0} | `{1}` |' -f $r.Name.Replace('|', '\|'), $r.Go)) }
        [void]$sb.AppendLine()
        [void]$sb.AppendLine('</details>')
        [void]$sb.AppendLine()
    }
    $out = Join-Path $goRoot 'docs/test-parity.md'
    [System.IO.File]::WriteAllText($out, $sb.ToString().TrimEnd() + "`n")
    Write-Host "Wrote $out"
}

if ($Strict -and @($its | Where-Object { $_.Status -in 'unmapped', 'todo' }).Count) { exit 1 }
